"""Build the ConvRot test ONNX graphs with TensorRT and check their outputs.

The fixtures (ONNX + ``fixtures.npz`` + ``manifest.json``) are generated by
ComfyUI-TensorRT-Reforge from an Anima ConvRot INT8 checkpoint. Point
``CONVROT_ONNX_DIR`` at that directory to run these tests; otherwise they skip.

ConvRot rows must be bit-exact against comfy-kitchen (the fixtures were made
with it). Fail-open rows have no plugin node and only need cos >= 0.999999
against the BF16 dense reference.
"""
from __future__ import annotations

import json
import os

import numpy as np
import pytest

onnx = pytest.importorskip("onnx")
trt = pytest.importorskip("tensorrt")
torch = pytest.importorskip("torch")

import trt_dit_plugins as tdp

ONNX_DIR = os.environ.get("CONVROT_ONNX_DIR")
pytestmark = pytest.mark.skipif(
    not ONNX_DIR or not torch.cuda.is_available(),
    reason="set CONVROT_ONNX_DIR (and a CUDA device) to run the ONNX fixtures",
)

_TORCH_DTYPE = {
    onnx.TensorProto.BFLOAT16: torch.bfloat16,
    onnx.TensorProto.FLOAT16: torch.float16,
    onnx.TensorProto.FLOAT: torch.float32,
}
_CONVROT = ("convrot_layer1.onnx", "convrot_layer2.onnx", "convrot_q_proj.onnx")
_FAILOPEN = ("failopen_nonconvrot_q_proj.onnx", "failopen_transposed_q_proj.onnx")


def _load(name):
    with open(os.path.join(ONNX_DIR, name), "rb") as f:
        model = onnx.load(f)
    with open(os.path.join(ONNX_DIR, "manifest.json")) as f:
        doc = json.load(f)
    manifest = {**doc["models"][name], "profile": doc["profile"]}
    fx = np.load(os.path.join(ONNX_DIR, "fixtures.npz"))
    return model, manifest, fx


def _dim_value(dim, m):
    return dim.dim_value if dim.HasField("dim_value") else m


def _build(model, profile):
    tdp.ensure_loaded()
    logger = trt.Logger(trt.Logger.WARNING)
    builder = trt.Builder(logger)
    net = builder.create_network(1 << int(trt.NetworkDefinitionCreationFlag.STRONGLY_TYPED))
    parser = trt.OnnxParser(net, logger)
    if not parser.parse(model.SerializeToString()):
        raise AssertionError([parser.get_error(i).desc() for i in range(parser.num_errors)])
    cfg = builder.create_builder_config()
    prof = builder.create_optimization_profile()
    for i in range(net.num_inputs):
        t = net.get_input(i)
        tail = tuple(t.shape[1:])
        prof.set_shape(t.name, (profile["min"], *tail),
                       (profile["opt"], *tail), (profile["max"], *tail))
    cfg.add_optimization_profile(prof)
    ser = builder.build_serialized_network(net, cfg)
    assert ser is not None, "engine build failed"
    return trt.Runtime(logger).deserialize_cuda_engine(ser)


def _run(engine, model, m, fx):
    """One execution at leading dim ``m``; returns {output name: bf16 tensor}."""
    ctx = engine.create_execution_context()
    io = {engine.get_tensor_name(i): engine.get_tensor_mode(engine.get_tensor_name(i))
          for i in range(engine.num_io_tensors)}
    tensors = {}
    for vi in list(model.graph.input) + list(model.graph.output):
        dims = [d for d in vi.type.tensor_type.shape.dim]
        shape = tuple(_dim_value(d, m) for d in dims)
        dtype = _TORCH_DTYPE[vi.type.tensor_type.elem_type]
        tensors[vi.name] = torch.empty(shape, dtype=dtype, device="cuda")
        if io[vi.name] == trt.TensorIOMode.INPUT:
            tensors[vi.name].copy_(torch.from_numpy(fx[f"{vi.name}_m{m}"].astype(np.float32)))
        ctx.set_tensor_address(vi.name, tensors[vi.name].data_ptr())
        ctx.set_input_shape(vi.name, shape)
    assert ctx.execute_async_v3(torch.cuda.current_stream().cuda_stream)
    torch.cuda.synchronize()
    return {n: t for n, t in tensors.items()
            if io[n] == trt.TensorIOMode.OUTPUT}


@pytest.mark.parametrize("name", _CONVROT)
def test_convrot_onnx_is_bit_exact(name):
    model, manifest, fx = _load(name)
    plugin_nodes = sum(1 for n in model.graph.node if n.domain == "dit-plugins")
    assert plugin_nodes == manifest["expected_plugin_nodes"] == 1
    engine = _build(model, manifest["profile"])
    for m in manifest["fixture_ms"]:
        outs = _run(engine, model, m, fx)
        for out_name, got in outs.items():
            want = fx[f"{out_name}_m{m}"].astype(np.float32)
            diff = np.abs(got.float().cpu().numpy() - want).max()
            assert diff == 0.0, (out_name, m, float(diff))


def test_convrot_all_onnx_is_bit_exact():
    model, manifest, fx = _load("convrot_all.onnx")
    assert sum(1 for n in model.graph.node if n.domain == "dit-plugins") == 3
    engine = _build(model, manifest["profile"])
    for m in manifest["fixture_ms"]:
        for out_name, got in _run(engine, model, m, fx).items():
            want = fx[f"{out_name}_m{m}"].astype(np.float32)
            assert np.array_equal(got.float().cpu().numpy(), want), (out_name, m)


@pytest.mark.parametrize("name", _FAILOPEN)
def test_failopen_onnx_has_no_plugin_and_matches_dense(name):
    model, manifest, fx = _load(name)
    assert not [n for n in model.graph.node if n.domain == "dit-plugins"]
    assert manifest["expected_plugin_nodes"] == 0
    engine = _build(model, manifest["profile"])
    m = manifest["fixture_ms"][0]
    for out_name, got in _run(engine, model, m, fx).items():
        want = fx[f"{out_name}_m{m}"].astype(np.float32)
        g = got.float().cpu().numpy()
        cos = float((g * want).sum() / (np.linalg.norm(g) * np.linalg.norm(want)))
        assert cos >= 0.999999, (out_name, cos)
